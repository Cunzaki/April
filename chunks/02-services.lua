            last_down[id] = key > 0 and key_down(key) or false
        end
        if capturing then
            last_down[id] = key > 0 and key_down(key) or false
            goto continue
        end
        if mode == 0 then
            if key > 0 then
                last_down[id] = key_down(key)
            end
            goto continue
        end
        if mode == 1 then
            if key > 0 then
                last_down[id] = key_down(key)
            end
            goto continue
