    local step = r < 0.5 and 0.08 or (r < 1 and 0.12 or 0.35)
    while r < max_r - 0.03 do
        radii[#radii + 1] = r
        r = r + step
        step = r < 1 and 0.12 or 0.35
    end
    radii[#radii + 1] = max_r
    return radii
