                pcall(menu.set, id, not cur)
            else
                pcall(function()
                    April.require("ui.gs_state").set(id, not cur)
                end)
            end
            pcall(function()
                April.require("core.menu_util").sync_master(id)
            end)
        end
        last_down[id] = down
        ::continue::
    end
