function M.label(vk)
    vk = tonumber(vk) or 0
    if vk <= 0 then return "none" end
    return M.NAMES[vk] or string.format("%02X", vk)
end

function M.chip(vk)
    return "[" .. M.label(vk) .. "]"
end

return M
